create table public.job_offers (
  id bigint generated by default as identity primary key,
  title text not null,
  company text not null,
  company_logo_url text,
  category text not null check (
    category in (
      'AI/ML',
      'JavaScript',
      'HTML',
      'PHP',
      'Ruby',
      'Python',
      'Java',
      '.NET',
      'Scala',
      'C',
      'Mobile',
      'Testing',
      'DevOps',
      'Admin',
      'UX/UI',
      'PM',
      'Game',
      'Analytics',
      'Security',
      'Data',
      'Go',
      'Support',
      'ERP',
      'Architecture',
      'Other'
    )
  ),
  location text not null,
  workplace text not null check (workplace in ('Remote', 'Hybrid', 'On-site')),
  employment_type text not null check (employment_type in ('Full-time', 'Contract')),
  salary text,
  tags text[] not null default '{}',
  source_url text unique,
  published_at timestamptz,
  applicants integer not null default 0 check (applicants >= 0),
  response_rate smallint not null default 0 check (response_rate between 0 and 100),
  applied boolean not null default false,
  responded boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create trigger job_offers_set_updated_at
before update on public.job_offers
for each row
execute function public.set_updated_at();

alter table public.job_offers enable row level security;

create policy "Anyone can view job offers"
on public.job_offers
for select
to anon, authenticated
using (true);

create policy "Authenticated users can create job offers"
on public.job_offers
for insert
to authenticated
with check (true);

create policy "Authenticated users can update job offers"
on public.job_offers
for update
to authenticated
using (true)
with check (true);

create policy "Authenticated users can delete job offers"
on public.job_offers
for delete
to authenticated
using (true);

grant select on table public.job_offers to anon;
grant select, insert, update, delete on table public.job_offers to authenticated;
grant usage, select on sequence public.job_offers_id_seq to authenticated;
