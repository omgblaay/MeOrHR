create or replace function public.record_job_offer_source_click(source_id bigint)
returns integer
language plpgsql
security definer
set search_path = ''
as $$
declare
  updated_count integer;
begin
  update public.job_offer_sources
  set click_count = click_count + 1
  where id = source_id
  returning click_count into updated_count;

  if updated_count is null then
    raise exception 'Job offer source not found';
  end if;

  return updated_count;
end;
$$;

revoke all on function public.record_job_offer_source_click(bigint) from public;
grant execute on function public.record_job_offer_source_click(bigint) to anon, authenticated;
