alter table public.job_offers
  add column confirmed_applicants integer not null default 0
    check (confirmed_applicants >= 0);

update public.job_offers
set confirmed_applicants = applicants;

create table public.job_offer_sources (
  id bigint generated by default as identity primary key,
  job_offer_id bigint not null references public.job_offers(id) on delete cascade,
  platform text not null check (
    platform in (
      'linkedin',
      'indeed',
      'stepstone',
      'justjoinit',
      'nofluffjobs',
      'pracuj',
      'glassdoor',
      'xing',
      'welcome_to_the_jungle',
      'wellfound',
      'eures',
      'company_career_page',
      'other'
    )
  ),
  url text not null unique,
  published_at timestamptz,
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  closed_at timestamptz,
  click_count integer not null default 0 check (click_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (job_offer_id, platform, url)
);

create index job_offer_sources_job_offer_id_idx
  on public.job_offer_sources(job_offer_id);

create trigger job_offer_sources_set_updated_at
before update on public.job_offer_sources
for each row
execute function public.set_updated_at();

insert into public.job_offer_sources (
  job_offer_id,
  platform,
  url,
  published_at,
  first_seen_at,
  last_seen_at
)
select
  id,
  source_platform,
  source_url,
  published_at,
  coalesce(published_at, created_at),
  updated_at
from public.job_offers
where source_url is not null
on conflict (url) do nothing;

alter table public.job_offer_sources enable row level security;

